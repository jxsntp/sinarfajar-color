import { test, expect } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import { randomUUID } from "node:crypto";
import { identity } from "../support/identity";

const db = new PrismaClient();
test.afterAll(() => db.$disconnect());
test("admin imports a mapped CSV, edits inventory, uploads a photo and evaluates the current catalog",async({page,request})=>{
  const slug = "browser-" + randomUUID();
  const org=await db.organization.create({data:{name:"Catalog fixture",slug}});
  await db.store.create({data:{organizationId:org.id,code:"PURI",name:"Test store"}});
  const admin=await identity(db,org.id);
  await page.goto("/login");
  await page.getByLabel("Organization",{exact:true}).fill(slug);
  await page.getByLabel("Email").fill(admin.email);
  await page.getByLabel("Password").fill(admin.password);
  await page.getByRole("button",{name:"Sign in"}).click();
  await page.getByRole("link",{name:"Administration",exact:true}).click();
  await page.getByRole("link",{name:"Manage product catalog"}).click();
  await page.getByLabel("CSV content").fill("Code,name,brand,category,goldColor,purity,price,onHand\nUI-1,Browser Band,Dawn,ring,white,18K,85000.25,4");
  await page.getByRole("button",{name:"Preview CSV"}).click();
  await page.locator("summary").filter({hasText:"Map columns"}).click();
  await page.getByRole("combobox",{name:"Source column for sku",exact:true}).selectOption("Code");
  await page.getByRole("button",{name:"Preview CSV"}).click();
  await page.getByRole("button",{name:"Import products"}).click();
  await expect(page.getByText("Imported 1 products")).toBeVisible();
  await page.getByLabel("Catalog record").selectOption("UI-1");
  await page.getByLabel("Units available").fill("7");
  await page.getByLabel("Display location",{exact:true}).fill("Case 4");
  const bytes=Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aKXkAAAAASUVORK5CYII=","base64");
  await page.getByLabel("Upload product photo").setInputFiles({name:"sample.png",mimeType:"image/png",buffer:bytes});
  await expect(page.getByLabel("Storage photo path")).toHaveValue(/\.png$/);
  await page.getByRole("button",{name:"Save changes"}).click();
  await expect.poll(()=>db.inventory.count({where:{organizationId:org.id,onHand:7,displayLocation:"Case 4"}})).toBe(1);
  const photo = await db.productImage.findFirstOrThrow({where:{organizationId:org.id}});
  const image=await request.get("http://127.0.0.1:25421/storage/v1/object/public/product-photos/"+photo.storagePath);
  expect(image.ok()).toBeTruthy();expect(await image.body()).toEqual(bytes);
  await page.getByRole("link",{name:"AI laboratory"}).click();
  await page.getByRole("button",{name:"Run local evaluation"}).click();
  await expect(page.locator("pre")).toContainText("UI-1");
  expect(await db.recommendationRun.count({where:{organizationId:org.id}})).toBe(0);
});
